import type { Section } from "@/lib/news/feeds";
import type { Story } from "@/lib/news/generate";
import { loadLatestBriefing } from "@/lib/news/load";

const SECTIONS: { id: Section; label: string; emoji: string }[] = [
  { id: "world", label: "World", emoji: "🌍" },
  { id: "hungary", label: "Hungary", emoji: "🇭🇺" },
  { id: "economy", label: "Economy & Markets", emoji: "📈" },
  { id: "tech", label: "Tech & AI", emoji: "💻" },
  { id: "positive", label: "Good News", emoji: "☀️" },
];

function readingMinutes(stories: Story[], closing: string): number {
  const words = [closing, ...stories.flatMap((s) => [s.title, s.summary, s.whyItMatters, s.perspectives ?? ""])]
    .join(" ")
    .split(/\s+/).length;
  return Math.max(1, Math.round(words / 220));
}

function formatDate(iso: string): string {
  return new Date(`${iso}T12:00:00Z`).toLocaleDateString("en-GB", {
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}

export default async function TodayPage() {
  const briefing = await loadLatestBriefing();

  if (!briefing) {
    return (
      <main className="mx-auto w-full max-w-xl px-4 py-16 text-center">
        <h1 className="font-serif text-3xl">No briefing yet</h1>
        <p className="mt-3 text-muted">
          Run <code className="rounded bg-card px-1.5 py-0.5">npm run briefing</code> to generate today&apos;s.
        </p>
      </main>
    );
  }

  return (
    <main className="mx-auto w-full max-w-xl px-4 pb-16 pt-10">
      <header className="mb-8">
        <p className="text-sm font-medium uppercase tracking-wider text-accent">Daily Briefing</p>
        <h1 className="mt-1 font-serif text-3xl leading-tight">{formatDate(briefing.date)}</h1>
        <p className="mt-2 text-sm text-muted">
          {readingMinutes(briefing.stories, briefing.closingQuestion)} min read · {briefing.stories.length} stories
        </p>
      </header>

      <nav className="-mx-4 mb-8 flex gap-2 overflow-x-auto px-4 pb-1 [scrollbar-width:none]">
        {SECTIONS.map((s) => (
          <a
            key={s.id}
            href={`#${s.id}`}
            className="shrink-0 rounded-full border border-line px-3 py-1.5 text-sm text-muted active:bg-card"
          >
            {s.emoji} {s.label}
          </a>
        ))}
      </nav>

      {SECTIONS.map((section) => {
        const stories = briefing.stories
          .filter((s) => s.section === section.id)
          .sort((a, b) => a.position - b.position);
        if (stories.length === 0) return null;
        return (
          <section key={section.id} id={section.id} className="mb-10 scroll-mt-6">
            <h2 className="mb-4 flex items-center gap-2 text-sm font-semibold uppercase tracking-wider text-muted">
              <span aria-hidden>{section.emoji}</span> {section.label}
            </h2>
            <div className="space-y-4">
              {stories.map((story) => (
                <StoryCard key={`${story.section}-${story.position}`} story={story} />
              ))}
            </div>
          </section>
        );
      })}

      <section className="rounded-2xl bg-accent-soft p-5">
        <p className="text-sm font-semibold uppercase tracking-wider text-accent">Worth thinking about</p>
        <p className="mt-2 font-serif text-xl leading-snug">{briefing.closingQuestion}</p>
      </section>

      <footer className="mt-10 text-center text-xs text-muted">
        Summaries generated by {briefing.model} from public RSS feeds. Always check the original source.
      </footer>
    </main>
  );
}

function StoryCard({ story }: { story: Story }) {
  return (
    <article className="rounded-2xl border border-line bg-card p-5">
      <h3 className="font-serif text-xl leading-snug">{story.title}</h3>
      <p className="mt-3 leading-relaxed">{story.summary}</p>

      <div className="mt-4 border-l-2 border-accent pl-3">
        <p className="text-xs font-semibold uppercase tracking-wider text-accent">Why it matters</p>
        <p className="mt-1 leading-relaxed text-muted">{story.whyItMatters}</p>
      </div>

      {story.perspectives && (
        <div className="mt-4 rounded-xl bg-background p-3">
          <p className="text-xs font-semibold uppercase tracking-wider text-muted">How outlets differ</p>
          <p className="mt-1 text-sm leading-relaxed">{story.perspectives}</p>
        </div>
      )}

      <div className="mt-4 flex flex-wrap gap-2">
        {story.sources.map((src) => (
          <a
            key={src.url}
            href={src.url}
            target="_blank"
            rel="noopener noreferrer"
            className="rounded-full bg-background px-3 py-1.5 text-sm font-medium active:opacity-70"
          >
            {src.name} ↗
          </a>
        ))}
      </div>
    </article>
  );
}
